function materialize(regionCode: string, rows: Seed[]): Question[] {
  const counters: Record<string, number> = {};
  return rows.map(
    ([category, level, factId, prompt, choices, explanation, source, alternatives]) => {
      const cell = `${category}-${level}`;
      counters[cell] = (counters[cell] ?? 0) + 1;
      return {
        id: `${regionCode}-${cell}-bank-${counters[cell]}`,
        regionCode,
        category,
        level,
        factId,
        prompt,
        choices,
        answerIndex: 0,
        explanation,
        source,
        ...(alternatives?.length ? { alternatives } : {}),
      };
    },
  );
}
